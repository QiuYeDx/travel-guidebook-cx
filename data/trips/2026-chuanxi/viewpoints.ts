const pendingPointReason = "D-7 尚未完成双地图坐标、停车入口和行驶方向复核";

function pendingPoint(
  reason = pendingPointReason,
): Extract<GeoRef, { kind: "none" }> {
  return { kind: "none", reason };
}

function routeInterval(
  routeLegId: string,
  fromLabel: string,
  toLabel: string,
): Extract<GeoRef, { kind: "route-interval" }> {
  return { kind: "route-interval", routeLegId, fromLabel, toLabel };
}

function pendingParking(level: ParkingLevel, note: string): ParkingProfile {
  return {
    level,
    verificationStatus: "needs-review",
    note,
  };
}

